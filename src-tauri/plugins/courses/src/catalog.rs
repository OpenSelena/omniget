use serde::{Deserialize, Serialize};

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlatformConfig {
    pub id: String,
    pub name: String,
    pub color: String,
    pub icon: String,
    pub login_methods: Vec<LoginMethodConfig>,
    pub commands: PlatformCommandsConfig,
    pub features: PlatformFeaturesConfig,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LoginMethodConfig {
    pub method_type: String,
    pub command: String,
    pub extra_fields: Vec<ExtraFieldConfig>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ExtraFieldConfig {
    pub key: String,
    pub label: String,
    pub placeholder: String,
    pub field_type: String,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct PlatformCommandsConfig {
    pub check_session: String,
    pub logout: String,
    pub list: String,
    pub refresh: String,
    pub download: String,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub cancel: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub search: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub curriculum: Option<String>,
}

#[derive(Debug, Default, Clone, Serialize, Deserialize)]
pub struct PlatformFeaturesConfig {
    #[serde(skip_serializing_if = "Option::is_none")]
    pub captcha_event: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub has_search: Option<bool>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub download_arg_name: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub list_returns_key: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub item_subtitle_field: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub session_display: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    pub string_ids: Option<bool>,
}

fn creds_method(cmd: &str) -> LoginMethodConfig {
    LoginMethodConfig {
        method_type: "credentials".to_string(),
        command: cmd.to_string(),
        extra_fields: vec![
            ExtraFieldConfig {
                key: "email".to_string(),
                label: "Email".to_string(),
                placeholder: "user@example.com".to_string(),
                field_type: "text".to_string(),
            },
            ExtraFieldConfig {
                key: "password".to_string(),
                label: "Password".to_string(),
                placeholder: "••••••••".to_string(),
                field_type: "password".to_string(),
            },
        ],
    }
}

fn token_method(cmd: &str) -> LoginMethodConfig {
    LoginMethodConfig {
        method_type: "token".to_string(),
        command: cmd.to_string(),
        extra_fields: vec![ExtraFieldConfig {
            key: "token".to_string(),
            label: "Bearer Token".to_string(),
            placeholder: "eyJhbGciOi...".to_string(),
            field_type: "text".to_string(),
        }],
    }
}

fn cookies_method(cmd: &str) -> LoginMethodConfig {
    LoginMethodConfig {
        method_type: "cookies".to_string(),
        command: cmd.to_string(),
        extra_fields: vec![ExtraFieldConfig {
            key: "cookies".to_string(),
            label: "Cookies".to_string(),
            placeholder: "Paste cookies or JSON...".to_string(),
            field_type: "textarea".to_string(),
        }],
    }
}

