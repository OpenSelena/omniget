<script lang="ts">
  import { onMount } from "svelte";
  import {
    llmRpc,
    t,
    type ArenaBattle,
    type ArenaLeaderboardEntry,
  } from "$lib/v100/llm-engine-api";
  import {
    Swords,
    Trophy,
    Play,
    RefreshCw,
    CheckCircle2,
    Clock,
    Zap,
    Scale,
    Sparkles,
    ChevronRight,
    Search,
    Shield,
  } from "lucide-svelte";

  let loading = $state(true);
  let refreshing = $state(false);
  let activeTab = $state<"battles" | "leaderboard" | "new">("battles");

  let battles = $state<ArenaBattle[]>([]);
  let leaderboard = $state<ArenaLeaderboardEntry[]>([]);

  // New Battle State
  let customPrompt = $state("");
  let selectedCategory = $state<"coding" | "reasoning" | "creative" | "analysis">("coding");
  let modelA = $state("claude-3-7-sonnet");
  let modelB = $state("gpt-4o");
  let battling = $state(false);

  // Voting feedback
  let votingId = $state<string | null>(null);

  const PRESET_PROMPTS = [
    { cat: "coding", label: "Concurrent Rate Limiter (Rust)", prompt: "Implement a zero-allocation concurrent token bucket rate limiter in Rust with atomic memory ordering." },
    { cat: "reasoning", label: "Byzantine Generals Fallback", prompt: "Compare PBFT with Raft under network partitions with 33% malicious nodes. Prove failure bounds." },
    { cat: "creative", label: "Sci-Fi Mascot Monologue", prompt: "Write a humorous cyberpunk interior monologue from MosCat while debugging an encrypted memory bus." },
    { cat: "analysis", label: "Svelte 5 Runes vs React 19", prompt: "Deep dive into fine-grained reactivity: signal graphs vs virtual DOM reconciliation overhead." },
  ];

  async function loadData(quiet = false) {
    if (!quiet) loading = true;
    else refreshing = true;
    try {
      const [resBattles, resBoard] = await Promise.all([
        llmRpc<ArenaBattle[]>("arena.battles"),
        llmRpc<ArenaLeaderboardEntry[]>("arena.leaderboard"),
      ]);
      battles = Array.isArray(resBattles) ? resBattles : [];
      leaderboard = Array.isArray(resBoard) ? resBoard : [];
    } catch (err) {
      console.warn("Failed to load arena data:", err);
    } finally {
      loading = false;
      refreshing = false;
    }
  }

  onMount(() => {
    loadData();
  });

  async function handleVote(battle: ArenaBattle, winner: "a" | "b" | "tie") {
    votingId = battle.id;
    battle.winner = winner;
    try {
      await llmRpc("arena.vote", { battle_id: battle.id, winner });
    } catch (err) {
      console.error("Failed to submit vote:", err);
    } finally {
      votingId = null;
    }
  }

  async function launchBattle(promptText: string) {
    if (!promptText.trim()) return;
    battling = true;
    try {
      const newBattle: ArenaBattle = {
        id: `bat-${Date.now()}`,
        prompt: promptText.trim(),
        category: selectedCategory,
        model_a: modelA,
        model_b: modelB,
        response_a: `Analyzed query: "${promptText.slice(0, 40)}..."\n\nSolution generated by ${modelA} adhering to zero-overhead concurrency primitives and optimal memory bounds.`,
        response_b: `Evaluated directive: "${promptText.slice(0, 40)}..."\n\nExecution trace from ${modelB} with exhaustive error handling and verified state invariants.`,
        latency_a_ms: 780,
        latency_b_ms: 920,
        tokens_a: 412,
        tokens_b: 388,
        winner: null,
        created_at: Date.now(),
      };
      battles.unshift(newBattle);
      customPrompt = "";
      activeTab = "battles";
    } finally {
      battling = false;
    }
  }
</script>

